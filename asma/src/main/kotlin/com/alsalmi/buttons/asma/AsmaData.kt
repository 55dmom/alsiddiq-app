/** Arabic search key: no harakat/tatweel, unified alef/ya/ta-marbuta. */
internal fun arKey(s: String): String = buildString {
    for (c in s) {
        val v = c.code
        if (v in 0x064B..0x065F || v == 0x0670 || v == 0x0640) continue
        append(
            when (v) {
                0x0622, 0x0623, 0x0625, 0x0671 -> '\u0627'
                0x0649 -> '\u064A'
                0x0629 -> '\u0647'
                else -> c
            }
        )
    }
}
